"""Write research/INDEX.md: one line per experiment in research/backtests/results, grouped by coin.

    python research/build_index.py

Each line takes the report's title and, where the report states one, its verdict (the text of a "Verdict",
"Decision" or "Result" heading, or the first sentence under it). Folders without a REPORT.md are listed as data.
"""

import re
from pathlib import Path

RESEARCH = Path(__file__).resolve().parent
RESULTS = RESEARCH / "backtests" / "results"
GROUPS = [("sol", "SOL"), ("eth", "ETH"), ("btc", "BTC"), ("aave", "AAVE"), ("trx", "TRX")]
VERDICT = re.compile(r"^#+\s*(verdict|decision|result|results|conclusion|bottom line)\b[:\s]*(.*)$", re.I)


def clean(text: str, limit: int = 140) -> str:
    text = re.sub(r"[*`]", "", text).replace("|", "/").strip(" .:-")
    return text if len(text) <= limit else text[: limit - 1].rsplit(" ", 1)[0] + "…"


def describe(folder: Path) -> tuple[str, str]:
    report = folder / "REPORT.md"
    if not report.exists():
        return folder.name.replace("_", " "), "data and tables only, no written report"
    lines = report.read_text(errors="replace").splitlines()
    title = next((clean(line.lstrip("# ")) for line in lines if line.startswith("# ")), folder.name)
    for index, line in enumerate(lines):
        match = VERDICT.match(line)
        if not match:
            continue
        if match.group(2).strip():
            return title, clean(match.group(2))
        following = next((l for l in lines[index + 1:] if l.strip() and not l.startswith(("|", "#", "```"))), "")
        return title, clean(re.split(r"(?<=[.!])\s", following.strip())[0])
    return title, ""


def group_of(name: str) -> str:
    for prefix, label in GROUPS:
        if name.startswith(prefix + "_"):
            return label
    return "Several coins and other"


rows: dict[str, list[str]] = {}
folders = sorted(path for path in RESULTS.iterdir() if path.is_dir())
for folder in folders:
    title, verdict = describe(folder)
    link = f"[{folder.name}](backtests/results/{folder.name}/" + ("REPORT.md)" if (folder / "REPORT.md").exists() else ")")
    rows.setdefault(group_of(folder.name), []).append(f"| {link} | {title} | {verdict} |")

out = ["# Research index", "",
       f"Every experiment in `backtests/results/`: {len(folders)} folders, generated by `python research/build_index.py`.",
       "Titles and verdicts are taken from each report; open the report for the numbers and caveats. Dollar figures",
       "in the reports are backtest units on a simulated account (see the [research README](README.md)).", ""]
for _, label in GROUPS + [("", "Several coins and other")]:
    if label not in rows:
        continue
    out += [f"## {label}", "", "| Folder | What was tested | Verdict |", "|---|---|---|", *rows[label], ""]
(RESEARCH / "INDEX.md").write_text("\n".join(out))
print(f"wrote research/INDEX.md: {len(folders)} experiments")
